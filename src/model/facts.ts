/** Варианты, где между строками стоит разделитель, и разделитель по умолчанию (индекс из блока «Разделитель»). */
const SEP_DEFAULT: Record<number, number> = { 0: 1, 1: 0, 3: 5 };
export const hasFactsSep = (v: number) => v in SEP_DEFAULT;
export const factsSep = (v: number, own: unknown) => (hasFactsSep(v) ? Number(own ?? SEP_DEFAULT[v]) : null);

/** Какой пресет сейчас собран: тот же вариант и тот же набор типов строк. */
export function factsPresetOf(v: number, rows: Item[]) {
  const sig = rows.map((r) => r.t ?? 'stat').join(',');
  return FACTS_PRESETS.findIndex((p) => p.v === v && p.rows.map((r) => r.t).join(',') === sig);
}
